// DATABASE_URL(또는 Vercel Postgres/Neon 연동 시 자동으로 들어오는 POSTGRES_URL)이 있으면 그 Postgres에 연결.
// 없으면 로컬 개발 서버(scripts/dev-api.ts)가 등록한 로컬 파일 DB(PGlite)를 사용.
// PGlite 코드를 여기 두지 않는 이유: Vercel은 함수가 참조하는 파일을 추적해 배포 묶음에 넣는데,
// 여기서 PGlite/.data 경로를 참조하면 로컬 DB 파일(테스트 계정의 비밀번호 해시 등)까지 배포에 포함됨
export interface Db {
  query<T = Record<string, any>>(sql: string, params?: unknown[]): Promise<T[]>;
}

export const SCHEMA = `
CREATE TABLE IF NOT EXISTS users (
    user_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login_id  VARCHAR(50) UNIQUE NOT NULL,
    password  VARCHAR(255) NOT NULL,
    username  VARCHAR(50)
);
CREATE TABLE IF NOT EXISTS body_size (
    user_id        BIGINT PRIMARY KEY,
    height         DOUBLE PRECISION,
    shoulder_width DOUBLE PRECISION,
    arm_length     DOUBLE PRECISION,
    leg_length     DOUBLE PRECISION
);
CREATE TABLE IF NOT EXISTS cloth_size (
    user_id       BIGINT PRIMARY KEY,
    shoulder      DOUBLE PRECISION,
    total_length  DOUBLE PRECISION,
    sleeve_length DOUBLE PRECISION,
    color         VARCHAR(20)
);
CREATE TABLE IF NOT EXISTS pants_size (
    user_id          BIGINT PRIMARY KEY,
    pants_length     DOUBLE PRECISION,
    waist            DOUBLE PRECISION,
    rise             DOUBLE PRECISION,
    color            VARCHAR(20)
);
-- 측정 기준 변경(두께·폭 → 둘레, 의류는 단면 실측)으로 추가된 열.
-- 이미 만들어진 DB에도 적용되도록 ADD COLUMN IF NOT EXISTS 로 둠.
-- 예전 열(body_depth, leg_thickness, waist_width, hip_width, thigh_thickness)은 기존 데이터 보존을 위해 지우지 않고 더 이상 쓰지 않음
ALTER TABLE body_size  ADD COLUMN IF NOT EXISTS chest_circ  DOUBLE PRECISION;
ALTER TABLE body_size  ADD COLUMN IF NOT EXISTS waist_circ  DOUBLE PRECISION;
ALTER TABLE body_size  ADD COLUMN IF NOT EXISTS hip_circ    DOUBLE PRECISION;
ALTER TABLE body_size  ADD COLUMN IF NOT EXISTS thigh_circ  DOUBLE PRECISION;
ALTER TABLE cloth_size ADD COLUMN IF NOT EXISTS chest_width DOUBLE PRECISION;
ALTER TABLE pants_size ADD COLUMN IF NOT EXISTS thigh_width DOUBLE PRECISION;
`;

let instance: Promise<Db> | null = null;
let localDb: (() => Promise<Db>) | null = null;

/** 로컬 개발 서버 전용: DATABASE_URL이 없을 때 쓸 DB를 등록 */
export function setLocalDb(factory: () => Promise<Db>) {
  localDb = factory;
}

export function getDb(): Promise<Db> {
  if (!instance) {
    instance = connect().catch((e) => { instance = null; throw e; });
  }
  return instance;
}

async function connect(): Promise<Db> {
  const url = process.env.DATABASE_URL || process.env.POSTGRES_URL;
  if (url) {
    const { Pool } = await import("pg");
    // 서버리스 함수는 인스턴스가 많이 뜰 수 있어 인스턴스당 연결 수를 작게 유지
    const pool = new Pool({ ...poolConfig(url), max: 3 });
    await pool.query(SCHEMA);
    return { query: async (sql, params) => (await pool.query(sql, params as any[])).rows };
  }
  if (localDb) return localDb();
  throw new Error("DATABASE_URL 환경변수가 설정되지 않았습니다.");
}

// Supabase는 자체 CA로 서명한 인증서를 써서 시스템 기본 CA로는 검증에 실패함.
// Supabase 대시보드에서 받은 CA 인증서(DATABASE_CA_CERT)로 검증하고,
// URL의 sslmode가 아래 ssl 설정을 덮어쓰므로 지움
export function poolConfig(url: string): { connectionString: string; ssl?: { ca: string } } {
  const u = new URL(url);
  if (!/\.supabase\.(co|com)$/.test(u.hostname)) return { connectionString: url };
  const ca = process.env.DATABASE_CA_CERT;
  if (!ca) throw new Error("Supabase 연결에는 DATABASE_CA_CERT 환경변수(Supabase CA 인증서 내용)가 필요합니다.");
  u.searchParams.delete("sslmode");
  return { connectionString: u.toString(), ssl: { ca: ca.replace(/\\n/g, "\n") } };
}
